-- Follow-up to P1.S3/P1.S4 — adds `observations.entered_measurement_system`.
--
-- ADR-0005 states its whole-unit conversion-rounding rule in terms of the
-- measurement system a volume was ENTERED in ("when a stored volume is
-- rendered in a measurement system other than the one it was entered in,
-- the converted result is rounded"). The P1.S3 schema stores only canonical
-- mL/kg (ADR-0004) plus `Profile.measurementSystem`, which SRS §3.10
-- explicitly lets a patient change — so the entry system was not
-- recoverable per row, and `convertVolumeForDisplay` in
-- packages/core/src/units/convert.ts (P1.S4) already takes `entrySystem`
-- as a REQUIRED parameter no caller could truthfully supply. This migration
-- is what makes that parameter satisfiable.
--
-- Zero rows exist in `observations` as of this migration (no P2 write path
-- has landed yet) — the cheapest moment this is fixable, per the same
-- reasoning schema-coverage.md already applies to every other "add it now,
-- before rows exist" call in P1.S3.
--
-- ============================================================================
-- Generated by `prisma migrate dev --create-only` from schema.prisma's
-- `Observation.enteredMeasurementSystem` field (see that field's own doc
-- comment for the shape/nullability rationale) against a database already
-- carrying the P1.S3 migration — this is the ordinary, Prisma-generated
-- path, unlike 20260905000000_init_schema_core's hand-authored one. It
-- needed no hand-editing of the generated DDL itself: a single additive
-- `ADD COLUMN`, nothing touching the sync_sequence trigger/default shape
-- that migration's own header comment warns about. Verified empirically
-- (not assumed) against a real Postgres 17 container, in this order:
--   1. Applied 20260905000000_init_schema_core to a fresh database.
--   2. `prisma migrate diff --from-config-datasource --to-schema
--      prisma/schema.prisma --script` against that live database produced
--      exactly the one `ALTER TABLE ... ADD COLUMN` below — no
--      `DROP SEQUENCE`, no default-stripping on `server_sequence`, so B1's
--      fix (schema-coverage.md "Sync sequence assignment") still holds
--      against this new column.
--   3. Applied this migration on top, then re-ran
--      `prisma migrate diff --from-config-datasource --to-schema
--      prisma/schema.prisma --exit-code` against the now-twice-migrated
--      database: exit 0, "No difference detected" — the exact regression
--      test `prisma.integration.spec.ts`'s "re-diffing the live, migrated
--      database against schema.prisma is empty" assertion pins down still
--      passes with this column present.
-- ============================================================================
--
-- No GRANT statement below, and that omission was VERIFIED, not assumed
-- (per this sprint's own instruction not to take ADR-0011's "no blanket
-- ALTER DEFAULT PRIVILEGES" note as settling the column case too). ADR-0011's
-- "no blanket ALTER DEFAULT PRIVILEGES" rule is about a NEW TABLE inheriting
-- nothing until granted explicitly — Postgres has no per-table default-
-- privilege mechanism that would auto-grant a freshly created table. A NEW
-- COLUMN on an EXISTING table is a different mechanism entirely: Postgres
-- table-level privileges (the unqualified `GRANT SELECT, INSERT, UPDATE ON
-- "observations" TO "ostomy_runtime"` in 20260905000000_init_schema_core,
-- which names no column list) apply to the table's columns as a set,
-- including ones added later by `ALTER TABLE ... ADD COLUMN` — there is no
-- per-column grant to forget here. Verified against a real Postgres 17
-- container: connected as `ostomy_runtime` after applying this exact
-- migration on top of 20260905000000_init_schema_core, with ZERO grant
-- statements added, and confirmed it can INSERT a row naming
-- `entered_measurement_system` explicitly, SELECT it back, and UPDATE it —
-- and that `information_schema.role_table_grants` for
-- (`ostomy_runtime`, `observations`) is still exactly `{INSERT, SELECT,
-- UPDATE}`, unchanged from before this migration (no DELETE, matching the
-- tombstoned-synced-entity grant `prisma.integration.spec.ts`'s
-- `EXPECTED_TABLE_GRANTS` already asserts). The `audit_events` grant model
-- (SELECT/INSERT, no UPDATE/DELETE) is untouched by this migration — it
-- does not touch that table at all.
ALTER TABLE "observations" ADD COLUMN "entered_measurement_system" "measurement_system" NOT NULL;
